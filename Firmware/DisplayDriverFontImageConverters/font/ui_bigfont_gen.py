#!/usr/bin/env python3
"""
ui_bigfont_gen.py: makes Core/Inc/ui/ui_font_big.h, the large font the screens' value pop-up uses,
with the same drawing code as st7789_fontgen.py (keep the two scripts in the same folder).

    python ui_bigfont_gen.py OpenSans-Semibold.ttf --size 40

The table has the driver's cell format (columns of size/2 pixels, each column top to bottom, MSB
first), so ui_render.c draws it like the 12/16/24 px fonts. If you change --size, set
CH_POPUP_SIZE in channel_screen.h to match.
"""
import argparse, os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import st7789_fontgen as fg

p = argparse.ArgumentParser()
p.add_argument("font")
p.add_argument("--size", type=int, default=40, help="cell height in pixels, even (default: %(default)s)")
p.add_argument("--fit", choices=("shrink", "condense"), default="shrink")
p.add_argument("--threshold", type=int, default=128)
p.add_argument("-o", "--output", default="ui_font_big.h")
a = p.parse_args()
if a.size % 2 or not 8 <= a.size <= 64:
    sys.exit("--size must be an even number from 8 to 64")

table, em, narrow, squeezed, clipped = fg.make_table(a.font, a.size, a.threshold, a.fit)
name = "ui_font_%d" % a.size
lines = ["/**",
         " * ui_font_big.h, generated by ui_bigfont_gen.py: the value pop-up's large font.",
         " * %d px: %s" % (a.size, fg.describe(a.font, em, None, narrow, squeezed, clipped)),
         " * Include only in ui_render.c: each file that includes it gets its own copy in flash.",
         " */", "",
         "#ifndef UI_FONT_BIG_H", "#define UI_FONT_BIG_H", "", "#include <stdint.h>", "",
         "#define UI_FONT_BIG_SIZE %d" % a.size, "#define UI_FONT_BIG %s // the table below, whatever its size" % name, "",
         "static const uint8_t %s[95][%d] =" % (name, len(table[0])), "{"]
for i, data in enumerate(table):
    ch = chr(32 + i)
    lines.append("    {%s}, /*%s*/" % (", ".join("0x%02X" % v for v in data), repr(ch).replace("*/", "* /")))
lines += ["};", "", "#endif", ""]
open(a.output, "w", encoding="ascii", newline="\n").write("\n".join(lines))
print("wrote %s: %d px, %d bytes" % (a.output, a.size, 95 * len(table[0])))
